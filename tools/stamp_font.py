def main():
    assert len(G) == 95, len(G)
    rows = []
    for c in range(32, 127):
        g = G[chr(c)]
        assert len(g) == 7 and all(len(r) == 5 and set(r) <= {'.', '#'} for r in g), chr(c)
        rows.append([int(r.replace('#', '1').replace('.', '0'), 2) for r in g])
    out = ['/* SPDX-License-Identifier: GPL-2.0-or-later */',
           '/* Generated by tools/stamp_font.py. GPL-2.0-or-later. Independently drawn',
           ' * 5x7 dot-matrix glyphs for printable ASCII 32-126: 7 row bytes per glyph,',
           ' * bit 4 is the leftmost column. */',
           '#ifndef FILM_FONT_H', '#define FILM_FONT_H',
           'static const unsigned char film_font5x7[95][7]={']
    for c, r in zip(range(32, 127), rows):
        out.append(' {' + ','.join(f'0x{b:02x}' for b in r) + '},' + (f' /* {chr(c)} */' if chr(c) not in '*/\\' else ''))
    out[-1] = out[-1].replace('},', '}', 1) if False else out[-1]
    out += ['};', '#endif', '']
    (Path(__file__).resolve().parent.parent / 'camera/film_font.h').write_text('\n'.join(out))
    # Preview sheet for review.
    if len(__import__('sys').argv) > 1:
        from PIL import Image
        im = Image.new('L', (16 * 6 * 4, 6 * 8 * 4), 0)
        for i, r in enumerate(rows):
            cx, cy = (i % 16) * 6, (i // 16) * 8
            for y, b in enumerate(r):
                for x in range(5):
                    if b >> (4 - x) & 1:
                        for dy in range(4):
                            for dx in range(4):
                                im.putpixel(((cx + x) * 4 + dx, (cy + y) * 4 + dy), 255)
        im.save(__import__('sys').argv[1])

if __name__ == '__main__':
    main()
